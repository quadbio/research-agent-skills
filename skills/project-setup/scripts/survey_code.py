#!/usr/bin/env python3
"""Draft a CODE_MAP.md: packages and modules, scripts and notebooks per folder, and code-health flags.

    survey_code.py <code_dir> [--max-depth 5]

For every Python module: first docstring line, number of functions and classes, line count. For every folder:
counts of Python, R, shell, workflow files and notebooks. Flags for the one-owner and small-function rules:
function names defined in more than one module, modules over 800 lines, modules whose docstring states no purpose (missing, or only date/author lines), files with
more classes than functions. Archived, legacy, deprecated and per-run snapshot (run001/) folders are
listed but not analysed. Prints Markdown;
the agent writes the purpose of each package and folder from the docstrings and READMEs.
"""
import argparse
import ast
import os
import re
import sys
from collections import defaultdict

SKIP_DIRS = {'.git', '.ipynb_checkpoints', '.pixi', '.snakemake', '.tmux_runtime', '.venv', '__pycache__', 'build', 'data', 'dist', 'log', 'logs', 'node_modules', 'output', 'outputs', 'results', 'scratch', 'slurm_logs', 'tmp', 'venv', 'wandb', 'work', 'worktrees'}
FROZEN_MARKERS = ("_archive", "archive", "_legacy", "legacy", "deprecated", "_old")
KINDS = {".py": "py", ".R": "R", ".r": "R", ".sh": "sh", ".smk": "smk", ".nf": "nf", ".ipynb": "ipynb"}
LARGE = 800


RUN_SNAPSHOT = re.compile(r"^run[_-]?\d{2,}$")     # per-run copies of scripts kept as provenance


def is_frozen(rel):
    return any(part.lower().startswith(FROZEN_MARKERS) or RUN_SNAPSHOT.match(part.lower()) for part in rel.split(os.sep))


def walk(root, max_depth):
    """Code folders as [(relative folder, file names)], plus the frozen folders that were skipped."""
    base = root.rstrip(os.sep).count(os.sep)
    found, frozen = [], []
    for d, dirs, files in os.walk(root):
        rel = os.path.relpath(d, root)
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
        if rel != "." and is_frozen(rel):
            frozen.append(rel)
            dirs[:] = []
            continue
        if d.count(os.sep) - base >= max_depth:
            dirs[:] = []
        found.append((rel, files))
    return found, frozen


def module_info(path):
    """(docstring first line, functions, classes, lines) for a Python file; None if it does not parse."""
    try:
        src = open(path, errors="ignore").read()
        tree = ast.parse(src)
    except (OSError, SyntaxError, ValueError):
        return None
    meta = re.compile(r"^\s*(date|author|created|updated|modified|version)\b\s*:?", re.I)
    doc = [ln.strip() for ln in (ast.get_docstring(tree) or "").splitlines() if ln.strip() and not meta.match(ln)]
    funcs = [n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
    classes = [n.name for n in tree.body if isinstance(n, ast.ClassDef)]
    first = re.sub(r"^(description|purpose|summary)\s*:\s*", "", doc[0], flags=re.I) if doc else ""
    return first, funcs, classes, src.count("\n") + 1


def survey(root, max_depth):
    folders, modules = {}, {}
    found, frozen = walk(root, max_depth)
    for rel, files in found:
        counts = defaultdict(int)
        for f in files:
            kind = KINDS.get(os.path.splitext(f)[1])
            if f == "Snakefile":
                kind = "smk"
            if kind:
                counts[kind] += 1
            if f.endswith(".py"):
                info = module_info(os.path.join(root, rel, f))
                if info:
                    modules[os.path.normpath(os.path.join(rel, f))] = info
        if counts:
            folders[rel] = dict(counts)
    return folders, modules, frozen


def flags(modules):
    owners = defaultdict(list)
    for mod, (_, funcs, _, _) in modules.items():
        for fn in funcs:
            if not fn.startswith("_") and fn not in {"main", "parse_args", "cli", "run"}:
                owners[fn].append(mod)
    dup = {fn: mods for fn, mods in owners.items() if len(mods) > 1}
    large = {m: i[3] for m, i in modules.items() if i[3] > LARGE}
    nodoc = [m for m, i in modules.items() if not i[0] and (i[1] or i[2]) and not m.endswith("__init__.py")]
    classy = [m for m, i in modules.items() if len(i[2]) > max(2, len(i[1]))]
    return dup, large, nodoc, classy


def render(root, folders, modules, frozen):
    out = [f"<!-- Draft generated by survey_code.py for {root}. Write the purpose of each package and folder. -->", ""]
    pkg_mods = {m: i for m, i in modules.items()
                if os.path.exists(os.path.join(root, os.path.dirname(m), "__init__.py")) or "src" in m.split(os.sep)[:-1]}
    out += ["## Packages and shared modules (folders with `__init__.py`, or inside any `src/`)", "", "| Module | Docstring | Functions | Classes | Lines |", "|---|---|---|---|---|"]
    for m, (doc, funcs, classes, n) in sorted(pkg_mods.items()):
        out.append(f"| `{m}` | {doc[:90] or '—'} | {len(funcs)} | {len(classes)} | {n} |")
    if not pkg_mods:
        out.append("| (no package with `__init__.py` found) | | | | |")
    out += ["", "## Folders with code", "", "| Folder | Python | R | Shell | Workflow | Notebooks |", "|---|---|---|---|---|---|"]
    for rel, c in sorted(folders.items()):
        out.append(f"| `{rel}` | {c.get('py', 0)} | {c.get('R', 0)} | {c.get('sh', 0)} | {c.get('smk', 0) + c.get('nf', 0)} | {c.get('ipynb', 0)} |")
    if frozen:
        out += ["", "Frozen (archive / legacy / deprecated, not analysed): " + ", ".join(f"`{f}`" for f in frozen[:15])
                + (" …" if len(frozen) > 15 else "")]
    dup, large, nodoc, classy = flags(modules)
    out += ["", "## Code-health flags", ""]
    out.append(f"- **Same function name in several modules** ({len(dup)}): candidates for one owner")
    out += [f"  - `{fn}`: " + ", ".join(f"`{m}`" for m in mods[:4]) + (" …" if len(mods) > 4 else "")
            for fn, mods in sorted(dup.items(), key=lambda kv: -len(kv[1]))[:15]]
    out.append(f"- **Modules over {LARGE} lines** ({len(large)}): " + ", ".join(f"`{m}` ({n})" for m, n in sorted(large.items(), key=lambda kv: -kv[1])[:10]))
    out.append(f"- **Modules without a purpose docstring** ({len(nodoc)}): " + ", ".join(f"`{m}`" for m in sorted(nodoc)[:10]) + (" …" if len(nodoc) > 10 else ""))
    out.append(f"- **More classes than functions** ({len(classy)}): " + ", ".join(f"`{m}`" for m in sorted(classy)[:10]))
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("code_dir")
    ap.add_argument("--max-depth", type=int, default=5)
    a = ap.parse_args()
    root = os.path.abspath(a.code_dir)
    print(render(root, *survey(root, a.max_depth)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
